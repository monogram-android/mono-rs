//! Deterministic Rust declaration emission.

#![allow(clippy::format_push_string)]

use crate::documentation::{
    emit as emit_docs, emit_indented as emit_indented_docs, indented_line, line as doc_line,
};
use crate::naming::{
    constant_name, field_name as rust_field, item_name, type_name as rust_type_name,
};
use crate::resolver::{Resolver, expression_head, generic_parameters, result_generic_parameters};
use crate::{GenerateError, Options};
use mono_tl_schema::{Argument, ArgumentValue, Combinator, CombinatorKind, Expression, Schema};
use std::collections::{BTreeMap, BTreeSet};

/// Generate formatted Rust source. Output is deterministic for a given model.
///
/// # Errors
///
/// Returns an error if a model expression cannot denote a Rust type, or if the
/// completed output is not valid Rust syntax.
pub fn generate(schema: &Schema, options: &Options) -> Result<String, GenerateError> {
    #[cfg(feature = "tracing")]
    tracing::debug!(
        constructor_count = schema.constructors.len(),
        function_count = schema.functions.len(),
        "Generating Rust from TL schema"
    );
    let mut out = String::new();
    out.push_str("// @generated by mono-tl-codegen. Do not edit.\n");
    doc_line(&mut out, &options.module_documentation);
    if let Some(layer) = schema.layer {
        doc_line(&mut out, &format!("Telegram schema layer {layer}."));
        out.push_str(&format!(
            "/// Layer declared by the source schema.\npub const LAYER: u32 = {layer};\n"
        ));
    }
    if let Some(url) = &schema.source.url {
        out.push_str(&format!(
            "/// Canonical source used to generate this module.\npub const SOURCE_URL: &str = {url:?};\n"
        ));
    }
    for item in &options.prelude {
        out.push_str(item);
        out.push('\n');
    }
    if uses_type_level_naturals(schema) {
        emit_natural_support(&mut out);
    }
    out.push('\n');
    let resolver = Resolver::new(schema, &options.type_mappings);

    emit_result_types(&mut out, schema, options.emit_codec)?;
    for combinator in schema
        .constructors
        .iter()
        .chain(&schema.functions)
        .filter(|item| !item.builtin)
    {
        emit_combinator(&mut out, combinator, &resolver, options.emit_codec)?;
    }

    match syn::parse_file(&out) {
        Ok(file) => Ok(prettyplease::unparse(&file)),
        Err(error) => {
            eprintln!("generated source prefix:\n{}", &out[..out.len().min(4_000)]);
            Err(error.into())
        }
    }
}

fn emit_result_types(
    out: &mut String,
    schema: &Schema,
    emit_codec: bool,
) -> Result<(), GenerateError> {
    let mut groups: BTreeMap<String, Vec<&Combinator>> = BTreeMap::new();
    for combinator in schema.constructors.iter().filter(|item| !item.builtin) {
        let Some(result) = expression_head(&combinator.result) else {
            continue;
        };
        groups
            .entry(result.to_owned())
            .or_default()
            .push(combinator);
    }
    for (result, constructors) in groups {
        let parameters = result_generic_parameters(constructors[0]);
        let rust_result = rust_type_name(&result);
        let generic_decl = generic_list_declaration(&parameters);
        doc_line(
            out,
            &format!("TL type `{result}`: https://core.telegram.org/type/{result}."),
        );
        derive(out, true);
        out.push_str(&format!("pub enum {rust_result}{generic_decl} {{\n"));
        for combinator in &constructors {
            let local_result_parameters = result_generic_parameters(combinator);
            if local_result_parameters.len() != parameters.len() {
                return Err(GenerateError::InvalidExpression(format!(
                    "constructors of `{result}` disagree on generic result arity"
                )));
            }
            let substitutions: BTreeMap<_, _> = local_result_parameters
                .into_iter()
                .zip(parameters.iter().cloned())
                .collect();
            let item_parameters = generic_parameters(combinator)
                .into_iter()
                .map(|parameter| {
                    substitutions.get(&parameter).cloned().ok_or_else(|| {
                        GenerateError::InvalidExpression(format!(
                            "generic parameter `{parameter}` of `{}` does not occur in its result",
                            combinator.name
                        ))
                    })
                })
                .collect::<Result<Vec<_>, _>>()?;
            let item_generics = generic_list_declaration(&item_parameters);
            emit_indented_docs(out, &combinator.documentation);
            out.push_str(&format!(
                "    {}({}{}),\n",
                rust_type_name(&combinator.name),
                item_name(combinator),
                item_generics,
            ));
        }
        out.push_str("}\n");
        if emit_codec {
            emit_result_codec(out, &result, &rust_result, &parameters, &constructors);
        }
        out.push('\n');
    }
    Ok(())
}

fn emit_combinator(
    out: &mut String,
    combinator: &Combinator,
    resolver: &Resolver<'_>,
    emit_codec: bool,
) -> Result<(), GenerateError> {
    emit_docs(out, &combinator.documentation);
    derive(out, false);
    let name = item_name(combinator);
    let generics = generic_parameters(combinator);
    let generic_decl = generic_declaration(&generics);
    let fields: Vec<_> = combinator
        .arguments
        .iter()
        .filter(|argument| !argument.implicit)
        .collect();
    let unused_generics = generics
        .iter()
        .filter(|generic| {
            !fields
                .iter()
                .any(|argument| argument_uses_generic(argument, generic))
        })
        .cloned()
        .collect::<Vec<_>>();
    if fields.is_empty() && unused_generics.is_empty() {
        out.push_str(&format!("pub struct {name} {{}}\n"));
    } else {
        out.push_str(&format!("pub struct {name}{generic_decl} {{\n"));
        for (index, argument) in fields.iter().enumerate() {
            let fallback = format!("field_{index}");
            let source_name = argument.name.as_deref().unwrap_or(&fallback);
            indented_line(
                out,
                argument
                    .description
                    .as_deref()
                    .unwrap_or(&format!("TL field `{source_name}`.")),
            );
            let field = rust_field(source_name);
            let ty = rust_argument_type(argument, &generics, resolver)?;
            out.push_str(&format!("    pub {field}: {ty},\n"));
        }
        if !unused_generics.is_empty() {
            out.push_str("    #[doc(hidden)]\n");
            out.push_str("    #[cfg_attr(feature = \"bon\", builder(default))]\n");
            out.push_str(&format!(
                "    pub _tl_marker: std::marker::PhantomData<fn() -> ({},)>,\n",
                unused_generics.join(", ")
            ));
        }
        out.push_str("}\n");
    }
    out.push_str(&format!("impl{generic_decl} {name}{generic_decl} {{\n"));
    let id = combinator.id;
    let high = id >> 16;
    let low = id & 0xffff;
    out.push_str(&format!(
        "    /// TL constructor number.\n    pub const ID: u32 = 0x{high:04x}_{low:04x};\n"
    ));
    out.push_str(&format!(
        "    /// Whether [`Self::ID`] was written explicitly in the source schema.\n    pub const ID_EXPLICIT: bool = {};\n",
        combinator.id_explicit
    ));
    out.push_str(&format!(
        "    /// Original namespace-qualified TL name.\n    pub const NAME: &'static str = {:?};\n",
        combinator.name
    ));
    out.push_str(&format!(
        "    /// Original TL result expression.\n    pub const RESULT: &'static str = {:?};\n",
        display_expr(&combinator.result)
    ));
    out.push_str(&format!(
        "    /// Layer of the containing schema, when declared by the input.\n    pub const SCHEMA_LAYER: Option<u32> = {:?};\n",
        combinator.layer.schema
    ));
    out.push_str(&format!(
        "    /// First layer, only when explicitly supplied by source metadata.\n    pub const INTRODUCED_LAYER: Option<u32> = {:?};\n",
        combinator.layer.introduced
    ));
    emit_flag_constants(out, &combinator.arguments);
    out.push_str("}\n");
    if emit_codec {
        emit_combinator_codec(out, combinator, &name, &generics, resolver)?;
    }
    out.push('\n');
    Ok(())
}

fn trait_generics(generics: &[String], bound: &str) -> (String, String) {
    if generics.is_empty() {
        (String::new(), String::new())
    } else {
        (
            format!(
                "<{}>",
                generics
                    .iter()
                    .map(|name| format!("{name}: {bound}"))
                    .collect::<Vec<_>>()
                    .join(", ")
            ),
            format!("<{}>", generics.join(", ")),
        )
    }
}

fn emit_result_codec(
    out: &mut String,
    tl_name: &str,
    rust_name: &str,
    generics: &[String],
    constructors: &[&Combinator],
) {
    let (encode_impl, use_generics) = trait_generics(generics, "crate::codec::TlEncode");
    out.push_str(&format!("impl{encode_impl} crate::codec::TlEncode for {rust_name}{use_generics} {{\n    fn encode(&self, encoder: &mut crate::codec::Encoder) -> Result<(), crate::codec::Error> {{\n        match self {{\n"));
    for constructor in constructors {
        out.push_str(&format!(
            "            Self::{}(value) => crate::codec::Boxed::encode_boxed(value, encoder),\n",
            rust_type_name(&constructor.name)
        ));
    }
    out.push_str("        }\n    }\n}\n");

    let (decode_impl, use_generics) = trait_generics(generics, "crate::codec::TlDecode");
    out.push_str(&format!("impl{decode_impl} crate::codec::TlDecode for {rust_name}{use_generics} {{\n    fn decode(decoder: &mut crate::codec::Decoder<'_>) -> Result<Self, crate::codec::Error> {{\n        decoder.nested(<Self as crate::codec::BoxedDecode>::decode_boxed)\n    }}\n}}\n"));
    out.push_str(&format!("impl{decode_impl} crate::codec::BoxedDecode for {rust_name}{use_generics} {{\n    fn decode_boxed(decoder: &mut crate::codec::Decoder<'_>) -> Result<Self, crate::codec::Error> {{\n        let offset = decoder.offset();\n        match decoder.read_u32()? {{\n"));
    for constructor in constructors {
        let variant = rust_type_name(&constructor.name);
        let item = item_name(constructor);
        let id = if use_generics.is_empty() {
            format!("{item}::ID")
        } else {
            format!("<{item}{use_generics}>::ID")
        };
        out.push_str(&format!(
            "            {id} => Ok(Self::{variant}(crate::codec::TlDecode::decode(decoder)?)),\n"
        ));
    }
    out.push_str("            constructor => Err(crate::codec::Error::UnknownConstructor { constructor, offset }),\n        }\n    }\n}\n");

    out.push_str(&format!("impl{encode_impl} crate::codec::BareEncode for {rust_name}{use_generics} {{\n    fn encode_bare(&self, encoder: &mut crate::codec::Encoder) -> Result<(), crate::codec::Error> {{\n        match self {{\n"));
    for constructor in constructors {
        out.push_str(&format!(
            "            Self::{}(value) => crate::codec::TlEncode::encode(value, encoder),\n",
            rust_type_name(&constructor.name)
        ));
    }
    out.push_str("        }\n    }\n}\n");
    out.push_str(&format!("impl{decode_impl} crate::codec::BareDecode for {rust_name}{use_generics} {{\n    fn decode_bare(decoder: &mut crate::codec::Decoder<'_>) -> Result<Self, crate::codec::Error> {{\n"));
    if let [constructor] = constructors {
        out.push_str(&format!(
            "        decoder.nested(|decoder| Ok(Self::{}(crate::codec::TlDecode::decode(decoder)?)))\n",
            rust_type_name(&constructor.name)
        ));
    } else {
        out.push_str(&format!("        let _ = decoder;\n        Err(crate::codec::Error::AmbiguousBareConstructor {{ type_name: {tl_name:?} }})\n"));
    }
    out.push_str("    }\n}\n");
}

fn emit_combinator_codec(
    out: &mut String,
    combinator: &Combinator,
    name: &str,
    generics: &BTreeSet<String>,
    resolver: &Resolver<'_>,
) -> Result<(), GenerateError> {
    let generic_names = generics.iter().cloned().collect::<Vec<_>>();
    let (encode_impl, use_generics) = trait_generics(&generic_names, "crate::codec::TlEncode");
    out.push_str(&format!("impl{encode_impl} crate::codec::TlEncode for {name}{use_generics} {{\n    fn encode(&self, encoder: &mut crate::codec::Encoder) -> Result<(), crate::codec::Error> {{\n        let _ = encoder;\n"));
    let visible = combinator
        .arguments
        .iter()
        .filter(|argument| !argument.implicit)
        .collect::<Vec<_>>();
    for (index, argument) in visible.iter().enumerate() {
        let field = rust_field(
            argument
                .name
                .as_deref()
                .unwrap_or(&format!("field_{index}")),
        );
        if let Some(condition) = &argument.condition {
            if let Some(bit) = condition.bit {
                let flags = rust_field(&condition.variable);
                out.push_str(&format!("        if crate::codec::flag_is_set(self.{flags}, {bit}) != self.{field}.is_some() {{ return Err(crate::codec::Error::InconsistentFlag {{ field: {field:?}, flags: {flags:?}, bit: {bit} }}); }}\n"));
                if !argument_is_true(argument) {
                    out.push_str(&format!("        if let Some(value) = &self.{field} {{\n"));
                    emit_encode_value(out, argument, "value", "            ", &visible[..index])?;
                    out.push_str("        }\n");
                }
                continue;
            }
        }
        emit_encode_value(
            out,
            argument,
            &format!("&self.{field}"),
            "        ",
            &visible[..index],
        )?;
    }
    out.push_str("        Ok(())\n    }\n}\n");
    out.push_str(&format!("impl{encode_impl} crate::codec::Boxed for {name}{use_generics} {{ const CONSTRUCTOR_ID: u32 = Self::ID; }}\n"));

    let (decode_impl, use_generics) = trait_generics(&generic_names, "crate::codec::TlDecode");
    out.push_str(&format!("impl{decode_impl} crate::codec::TlDecode for {name}{use_generics} {{\n    fn decode(decoder: &mut crate::codec::Decoder<'_>) -> Result<Self, crate::codec::Error> {{\n        let _ = decoder;\n"));
    for (index, argument) in visible.iter().enumerate() {
        let field = rust_field(
            argument
                .name
                .as_deref()
                .unwrap_or(&format!("field_{index}")),
        );
        let decoded = decode_value(argument, &visible[..index])?;
        if let Some(condition) = &argument.condition {
            if let Some(bit) = condition.bit {
                let flags = rust_field(&condition.variable);
                let decoded = if argument_is_true(argument) {
                    "crate::codec::BareDecode::decode_bare(decoder)?".into()
                } else {
                    decoded
                };
                out.push_str(&format!("        let {field} = if crate::codec::flag_is_set({flags}, {bit}) {{ Some({decoded}) }} else {{ None }};\n"));
                continue;
            }
        }
        out.push_str(&format!("        let {field} = {decoded};\n"));
    }
    out.push_str("        Ok(Self {\n");
    for (index, argument) in visible.iter().enumerate() {
        let field = rust_field(
            argument
                .name
                .as_deref()
                .unwrap_or(&format!("field_{index}")),
        );
        out.push_str(&format!("            {field},\n"));
    }
    let unused = generic_names
        .iter()
        .filter(|generic| {
            !visible
                .iter()
                .any(|argument| argument_uses_generic(argument, generic))
        })
        .collect::<Vec<_>>();
    if !unused.is_empty() {
        out.push_str("            _tl_marker: std::marker::PhantomData,\n");
    }
    out.push_str("        })\n    }\n}\n");

    if matches!(combinator.kind, CombinatorKind::Function) {
        let response = resolver.render(&combinator.result, generics)?;
        out.push_str(&format!("impl{encode_impl} crate::codec::RpcMethod for {name}{use_generics} where {response}: crate::codec::TlDecode {{\n    type Response = {response};\n    const METHOD_NAME: &'static str = Self::NAME;\n    const RESULT_TYPE: &'static str = Self::RESULT;\n}}\n"));
    }
    Ok(())
}

fn argument_is_true(argument: &Argument) -> bool {
    matches!(&argument.value, ArgumentValue::Type { expression } if expression_head(expression).is_some_and(|name| name == "true"))
}

fn emit_encode_value(
    out: &mut String,
    argument: &Argument,
    access: &str,
    indent: &str,
    previous: &[&Argument],
) -> Result<(), GenerateError> {
    match &argument.value {
        ArgumentValue::Type { expression }
            if expression_head(expression)
                .is_some_and(|name| matches!(name, "bytes" | "Bytes")) =>
        {
            out.push_str(&format!(
                "{indent}crate::codec::encode_bytes({access}, encoder)?;\n"
            ));
        }
        ArgumentValue::Type {
            expression: Expression::Bare { .. },
        } => out.push_str(&format!(
            "{indent}crate::codec::BareEncode::encode_bare({access}, encoder)?;\n"
        )),
        ArgumentValue::Type { .. } => out.push_str(&format!(
            "{indent}crate::codec::TlEncode::encode({access}, encoder)?;\n"
        )),
        ArgumentValue::Repetition { multiplicity, .. } => {
            let count = natural_count(multiplicity.as_ref(), previous, "self.")?;
            out.push_str(&format!("{indent}crate::codec::validate_dependent_len({count}, ({access}).len())?;\n{indent}for value in {access} {{ crate::codec::TlEncode::encode(value, encoder)?; }}\n"));
        }
    }
    Ok(())
}

fn decode_value(argument: &Argument, previous: &[&Argument]) -> Result<String, GenerateError> {
    Ok(match &argument.value {
        ArgumentValue::Type { expression }
            if expression_head(expression)
                .is_some_and(|name| matches!(name, "bytes" | "Bytes")) =>
        {
            "crate::codec::decode_bytes(decoder)?".into()
        }
        ArgumentValue::Type {
            expression: Expression::Bare { .. },
        } => "crate::codec::BareDecode::decode_bare(decoder)?".into(),
        ArgumentValue::Type { .. } => "crate::codec::TlDecode::decode(decoder)?".into(),
        ArgumentValue::Repetition { multiplicity, .. } => {
            let count = natural_count(multiplicity.as_ref(), previous, "")?;
            let values = "(0..count).map(|_| crate::codec::TlDecode::decode(decoder)).collect::<Result<Vec<_>, crate::codec::Error>>()?";
            if matches!(multiplicity, Some(Expression::Nat { .. })) {
                format!(
                    "{{ let count = {count}; decoder.validate_vector_len(count)?; let values = {values}; values.try_into().map_err(|values: Vec<_>| crate::codec::Error::DependentLength {{ declared: count, actual: values.len() }})? }}"
                )
            } else {
                format!("{{ let count = {count}; decoder.validate_vector_len(count)?; {values} }}")
            }
        }
    })
}

fn natural_count(
    multiplicity: Option<&Expression>,
    previous: &[&Argument],
    prefix: &str,
) -> Result<String, GenerateError> {
    if let Some(expression) = multiplicity {
        return natural_expression(expression, prefix);
    }
    let (index, argument) = previous
        .iter()
        .enumerate()
        .rev()
        .find(|(_, argument)| {
            matches!(
                argument.value,
                ArgumentValue::Type {
                    expression: Expression::Hash
                }
            )
        })
        .ok_or_else(|| {
            GenerateError::InvalidExpression("repetition has no preceding natural count".into())
        })?;
    let field = rust_field(
        argument
            .name
            .as_deref()
            .unwrap_or(&format!("field_{index}")),
    );
    Ok(format!(
        "usize::try_from({prefix}{field}).map_err(|_| crate::codec::Error::InvalidNatural {{ value: u64::from({prefix}{field}) }})?"
    ))
}

fn natural_expression(expression: &Expression, prefix: &str) -> Result<String, GenerateError> {
    match expression {
        Expression::Ident { name } => Ok(format!(
            "usize::try_from({prefix}{}).map_err(|_| crate::codec::Error::InvalidNatural {{ value: u64::from({prefix}{}) }})?",
            rust_field(name),
            rust_field(name)
        )),
        Expression::Nat { value } => Ok(format!("{value}usize")),
        Expression::Add { left, right } => Ok(format!(
            "({} + {})",
            natural_expression(left, prefix)?,
            natural_expression(right, prefix)?
        )),
        _ => Err(GenerateError::InvalidExpression(
            "unsupported repetition multiplicity".into(),
        )),
    }
}

fn emit_flag_constants(out: &mut String, arguments: &[mono_tl_schema::Argument]) {
    let mut constants = BTreeSet::new();
    collect_flag_constants(out, arguments, &mut Vec::new(), &mut constants);
}

fn collect_flag_constants(
    out: &mut String,
    arguments: &[mono_tl_schema::Argument],
    path: &mut Vec<String>,
    constants: &mut BTreeSet<String>,
) {
    for (index, argument) in arguments.iter().enumerate() {
        let field = argument
            .name
            .clone()
            .unwrap_or_else(|| format!("field_{index}"));
        path.push(field);
        if let Some(condition) = &argument.condition {
            if let Some(bit) = condition.bit {
                let base = format!("{}_FLAG", constant_name(&path.join("_")));
                let mut name = base.clone();
                let mut suffix = 2;
                while !constants.insert(name.clone()) {
                    name = format!("{base}_{suffix}");
                    suffix += 1;
                }
                out.push_str(&format!(
                    "    /// Mask for `{}` bit {bit} controlling `{}`.\n    pub const {name}: u32 = 1_u32 << {bit};\n",
                    condition.variable,
                    path.join(".")
                ));
            }
        }
        if let ArgumentValue::Repetition { arguments, .. } = &argument.value {
            collect_flag_constants(out, arguments, path, constants);
        }
        path.pop();
    }
}

fn derive(out: &mut String, result_type: bool) {
    out.push_str("#[derive(Clone, Debug, PartialEq)]\n#[cfg_attr(feature = \"serde\", derive(serde::Serialize, serde::Deserialize))]\n");
    if !result_type {
        out.push_str("#[cfg_attr(feature = \"bon\", derive(bon::Builder))]\n");
    }
}

fn generic_declaration(generics: &BTreeSet<String>) -> String {
    generic_list_declaration(&generics.iter().cloned().collect::<Vec<_>>())
}

fn generic_list_declaration(generics: &[String]) -> String {
    if generics.is_empty() {
        String::new()
    } else {
        format!("<{}>", generics.join(", "))
    }
}

fn rust_argument_type(
    argument: &mono_tl_schema::Argument,
    generics: &BTreeSet<String>,
    resolver: &Resolver<'_>,
) -> Result<String, GenerateError> {
    let rust_type = if let ArgumentValue::Repetition {
        multiplicity,
        arguments,
    } = &argument.value
    {
        let mut fields = arguments
            .iter()
            .map(|field| rust_argument_type(field, generics, resolver))
            .collect::<Result<Vec<_>, _>>()?;
        let element = match fields.len() {
            0 => "()".into(),
            1 => fields.pop().expect("one repetition field"),
            _ => format!("({})", fields.join(", ")),
        };
        if let Some(Expression::Nat { value }) = multiplicity {
            format!("[{element}; {value}]")
        } else {
            format!("Vec<{element}>")
        }
    } else {
        let ArgumentValue::Type { expression } = &argument.value else {
            unreachable!("repetition handled above")
        };
        resolver.render(expression, generics)?
    };
    Ok(if argument.condition.is_some() {
        format!("Option<{rust_type}>")
    } else {
        rust_type
    })
}

fn display_expr(expression: &Expression) -> String {
    match expression {
        Expression::Ident { name } => name.clone(),
        Expression::Nat { value } => value.to_string(),
        Expression::Hash => "#".into(),
        Expression::Add { left, right } => {
            format!("({} + {})", display_expr(left), display_expr(right))
        }
        Expression::Bare { inner } => format!("%{}", display_expr(inner)),
        Expression::Bang { inner } => format!("!{}", display_expr(inner)),
        Expression::Apply {
            constructor,
            arguments,
        } => format!(
            "{}<{}>",
            display_expr(constructor),
            arguments
                .iter()
                .map(display_expr)
                .collect::<Vec<_>>()
                .join(", ")
        ),
    }
}

fn argument_uses_generic(argument: &mono_tl_schema::Argument, generic: &str) -> bool {
    match &argument.value {
        ArgumentValue::Type { expression } => expression_uses_generic(expression, generic),
        ArgumentValue::Repetition { arguments, .. } => arguments
            .iter()
            .any(|argument| argument_uses_generic(argument, generic)),
    }
}

fn expression_uses_generic(expression: &Expression, generic: &str) -> bool {
    match expression {
        Expression::Ident { name } => rust_type_name(name) == generic,
        Expression::Apply {
            constructor,
            arguments,
        } => {
            expression_uses_generic(constructor, generic)
                || arguments
                    .iter()
                    .any(|argument| expression_uses_generic(argument, generic))
        }
        Expression::Add { left, right } => {
            expression_uses_generic(left, generic) || expression_uses_generic(right, generic)
        }
        Expression::Bare { inner } | Expression::Bang { inner } => {
            expression_uses_generic(inner, generic)
        }
        Expression::Nat { .. } | Expression::Hash => false,
    }
}

fn uses_type_level_naturals(schema: &Schema) -> bool {
    schema
        .constructors
        .iter()
        .chain(&schema.functions)
        .any(|combinator| {
            combinator.arguments.iter().any(|argument| {
                argument.implicit
                    && matches!(
                        &argument.value,
                        ArgumentValue::Type {
                            expression: Expression::Hash
                        }
                    )
            })
        })
}

fn emit_natural_support(out: &mut String) {
    out.push_str(
        "#[doc(hidden)]\n\
         pub mod __tl {\n\
             #[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]\n\
             #[cfg_attr(feature = \"serde\", derive(serde::Serialize, serde::Deserialize))]\n\
             pub struct Nat<const N: u64>;\n\
             #[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]\n\
             #[cfg_attr(feature = \"serde\", derive(serde::Serialize, serde::Deserialize))]\n\
             pub struct Add<L, R>(pub std::marker::PhantomData<fn() -> (L, R)>);\n\
         }\n",
    );
}

#[cfg(test)]
mod tests {
    use super::*;
    use mono_tl_schema::Source;

    #[test]
    fn output_is_valid_and_documented() {
        let schema = mono_tl_schema::parse(
            "// @description A documented constructor.\n\
             // @param next The next value.\n\
             // @see https://example.invalid/type/a\n\
             a#01020304 next:A fallback:int = A;\n\
             ---functions---\n\
             // @description Fetches an A.\n\
             // @param id Object identifier.\n\
             a.get#05060708 id:long = A;",
            Source::default(),
        )
        .unwrap();
        let code = generate(&schema, &Options::default()).unwrap();
        assert!(code.contains("pub enum A"));
        assert!(code.contains("///A documented constructor."));
        assert!(code.contains("///The next value."));
        assert!(code.contains("///TL field `fallback`."));
        assert!(code.contains("///Related protocol documentation:"));
        assert!(code.contains("pub struct AGetRequest"));
        assert!(code.contains("///Fetches an A."));
        assert!(code.contains("///Object identifier."));
        assert!(code.contains("Official Telegram documentation"));
    }
}
